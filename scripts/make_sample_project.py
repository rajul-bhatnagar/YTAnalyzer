"""Build a sample project from synthetic fixture media and copy its output manifest to docs/sample_manifest.json.

Runs the whole local pipeline with no AI and no network: inspection -> audio mix -> signals-only analysis ->
one approved highlight -> Short (fast preset) -> thumbnails + template creator package. Uses a temporary studio
folder; nothing is written into the repository except docs/sample_manifest.json.

    .venv\\Scripts\\python.exe scripts\\make_sample_project.py
"""

from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline import ffmpeg_tools as fx  # noqa: E402
from pipeline.job_manager import JobRunner  # noqa: E402
from pipeline.models import TrackRole  # noqa: E402
from pipeline.paths import StudioPaths  # noqa: E402
from pipeline.project_service import StudioService  # noqa: E402


def make_media(out: Path) -> Path:
    """90 s synthetic 'gameplay': one event at 40 s (loud burst + hard cut); 3 audio tracks (mix, game, mic)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    fx.ffmpeg(["-y", "-v", "error",
               "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=30:duration=40",
               "-f", "lavfi", "-i", "smptehdbars=size=1280x720:rate=30:duration=15",
               "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=30:duration=35",
               "-f", "lavfi", "-i", "sine=f=220:d=90:sample_rate=48000",
               "-f", "lavfi", "-i", "anoisesrc=d=90:c=pink:r=48000:a=0.7",
               "-f", "lavfi", "-i", "anullsrc=r=48000:cl=mono",
               "-filter_complex",
               "[0:v][1:v][2:v]concat=n=3:v=1:a=0[v];[3:a]volume=0.05[bg];"
               "[4:a]volume='if(between(t,40,41),1,0)':eval=frame[b];"
               "[bg][b]amix=inputs=2:normalize=0,aformat=channel_layouts=stereo,asplit=2[g1][g2];"
               "[5:a]atrim=end=90,asplit=2[m1][m2];[g1][m1]amix=inputs=2:normalize=0[c]",
               "-map", "[v]", "-map", "[c]", "-map", "[g2]", "-map", "[m2]",
               "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p", "-c:a", "aac", "-t", "90", str(out)],
              timeout=600)
    return out


def run(svc: StudioService, start, *args, **kw) -> None:
    job = start(*args, **kw)
    if not svc.runner.wait_idle(1800):
        raise SystemExit("timed out")
    j = svc.jobs.get_job(job)
    if j["state"] in ("FAILED", "CANCELLED"):
        raise SystemExit(f"{start.__name__} failed: {j['error_summary']}")


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="yt_sample_") as tmp:
        paths = StudioPaths(Path(tmp) / "studio")
        paths.ensure()
        shutil.copy(ROOT / "config" / "default_settings.json", paths.default_settings_file)
        svc = StudioService(paths, runner=JobRunner(), configure_logging=False)
        src = make_media(paths.raw_input / "Sample Game" / "sample_recording.mp4")
        pid = svc.create_project(src, "Sample Game", "Custom", "en", "Synthetic fixture: one event at 40 s")
        run(svc, svc.start_inspection, pid)
        svc.save_track_roles(pid, {0: TrackRole.COMBINED_MIX, 1: TrackRole.GAME, 2: TrackRole.MIC})
        svc.save_project_settings(pid, {"ai.provider": "none", "shorts.quality": "fast",
                                        "transcription.source": "none"})
        run(svc, svc.start_longform, pid, "audio")
        run(svc, svc.start_analysis, pid)
        top = svc.highlights(pid)[0]
        svc.update_highlight(top["id"], status="approved", hook="Sample hook", title="Sample highlight")
        run(svc, svc.start_content, pid, "shorts")
        run(svc, svc.start_content, pid, "assets")
        manifest = paths.project_work_dir(svc.get_project(pid)["folder_name"]) / "manifest.json"
        data = json.loads(manifest.read_text("utf-8"))
        data["_note"] = ("Generated by scripts/make_sample_project.py from synthetic media on the dev PC "
                         "(CPU, no AI, no network). Paths are relative to the studio folder.")
        out = ROOT / "docs" / "sample_manifest.json"
        out.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
